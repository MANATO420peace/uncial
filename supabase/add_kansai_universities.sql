-- 関西圏の大学を追加
-- Supabase SQL Editor で実行してください
-- ※ 既存の大学と重複しないよう NOT EXISTS で確認しています

INSERT INTO universities (name)
SELECT name FROM (VALUES
  -- 関関同立（追加分）
  ('同志社大学'),
  ('立命館大学'),

  -- 産近甲龍
  ('京都産業大学'),
  ('近畿大学'),
  ('甲南大学'),
  ('龍谷大学'),

  -- 摂神追桃
  ('摂南大学'),
  ('神戸学院大学'),
  ('追手門学院大学'),
  ('桃山学院大学'),

  -- 国公立（関西）
  ('大阪公立大学'),
  ('京都府立大学'),
  ('京都工芸繊維大学'),
  ('兵庫県立大学'),
  ('奈良女子大学'),
  ('奈良県立大学'),
  ('滋賀大学'),
  ('滋賀県立大学'),
  ('和歌山大学'),
  ('大阪教育大学'),

  -- 私立（その他関西）
  ('同志社女子大学'),
  ('京都女子大学'),
  ('神戸女学院大学'),
  ('武庫川女子大学'),
  ('関西外国語大学'),
  ('京都外国語大学'),
  ('大阪経済大学'),
  ('大阪工業大学'),
  ('立命館アジア太平洋大学'),
  ('兵庫医科大学'),
  ('大阪医科薬科大学')
) AS new_universities(name)
WHERE NOT EXISTS (
  SELECT 1 FROM universities WHERE universities.name = new_universities.name
);
